const contentTypes = `<?xml version="1.0" encoding="utf-8"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension=".json" ContentType="application/json" />
  <Default Extension=".js" ContentType="application/javascript" />
  <Default Extension=".md" ContentType="text/markdown" />
  <Default Extension=".png" ContentType="image/png" />
  <Default Extension=".vsixmanifest" ContentType="text/xml" />
  <Default Extension=".txt" ContentType="text/plain" />
</Types>
`;

/** @param {string} dir @param {string} base @returns {{ name: string, data: Buffer }[]} */
function collect(dir, base) {
  const result = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const full = path.join(dir, entry.name);
    const name = `${base}/${entry.name}`;
    if (entry.isDirectory()) result.push(...collect(full, name));
    else result.push({ name, data: fs.readFileSync(full) });
  }
  return result;
}

const files = [
  { name: '[Content_Types].xml', data: contentTypes },
  { name: 'extension.vsixmanifest', data: manifest },
  ...collect(extensionDir, 'extension').filter((file) => /\.(js|json|md|png|txt)$/.test(file.name)),
];

// package.json обязан идти первым после манифеста — так делает vsce, и так надёжнее для старых установщиков.
files.sort((a, b) => {
  const rank = (name) => (name === '[Content_Types].xml' ? 0 : name === 'extension.vsixmanifest' ? 1 : name === 'extension/package.json' ? 2 : 3);
  return rank(a.name) - rank(b.name) || a.name.localeCompare(b.name);
});

const output = makeZip(files);
const distDir = path.join(root, 'dist');
fs.mkdirSync(distDir, { recursive: true });
const outFile = path.join(distDir, `${pkg.name}-${pkg.version}.vsix`);
fs.writeFileSync(outFile, output);

console.log(`собрано: ${outFile}`);
console.log(`файлов: ${files.length}, размер: ${(output.length / 1024).toFixed(1)} КБ`);
for (const file of files) console.log(`  ${file.name}`);
